import type { TranslateNS } from "@deepseek-ai/dsh-client-ui-slots";

export type UsageLocaleKey = keyof typeof en;
export type Translate = (key: UsageLocaleKey, params?: Readonly<Record<string, string | number>>) => string;

export function translator(raw: TranslateNS<"usage-stats"> | undefined): Translate {
	return (key, params) => {
		let value = raw?.(key) ?? key;
		if (params !== undefined) {
			for (const [name, replacement] of Object.entries(params)) {
				value = value.replaceAll(`{${name}}`, String(replacement));
			}
		}
		return value;
	};
}
